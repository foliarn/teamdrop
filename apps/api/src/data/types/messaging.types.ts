import type { OccurrenceKey } from './event.types';

/** Kind of conversation (BR-MSG-01). DB enum `conversation_kind`. Direct conversations are PENDING-TEAM. */
export type ConversationKind = 'occurrence' | 'circle' | 'community';

/** Fixed list of reaction codes (BR-MSG-02). The front end shows the glyph. */
export const REACTION_CODES = [
  'thumbs_up',
  'thumbs_down',
  'laugh',
  'surprised',
  'angry',
  'smile',
  'heart',
] as const;

/** One reaction code (BR-MSG-02). */
export type ReactionCode = (typeof REACTION_CODES)[number];

/** Maximum length of a message body, in characters (BR-MSG-02). */
export const MESSAGE_MAX_LENGTH = 4000;

/** The target a conversation belongs to (BR-MSG-01). */
export type ConversationTarget =
  | { circleId: string }
  | { communityId: string }
  | { occurrence: OccurrenceKey };

/** Author of a message, or `null` for a deleted user (BR-GDP-04). */
export type MessageSender = {
  userId: string;
  username: string;
  avatarPath: string | null;
} | null;

/** Message a reply points to. `hidden` when its author is blocked with the viewer (BR-SOC-02, BR-SOC-04). */
export type ReplyPreview =
  | {
      messageId: string;
      hidden: false;
      sender: MessageSender;
      /** The first 200 characters of the body. */
      bodyPreview: string;
    }
  | { messageId: string; hidden: true };

/** Reactions of one code on a message, as seen by the viewer (blocked users left out). */
export type ReactionSummary = {
  code: ReactionCode;
  count: number;
  reactedByMe: boolean;
};

/** A message as seen by a viewer (BR-MSG-02). */
export type ChatMessage = {
  id: string;
  conversationId: string;
  clientMessageId: string;
  sender: MessageSender;
  body: string;
  createdAt: Date;
  /** `null` when never edited (BR-MSG-02). */
  editedAt: Date | null;
  /** `null` when the message is not a reply, or its target was deleted (BR-MSG-03). */
  replyTo: ReplyPreview | null;
  reactions: ReactionSummary[];
};

/** Input of `MessageRepository.sendMessage` (BR-TECH-08). */
export type SendMessageInput = {
  /** UUID generated by the client, unique per sender; a re-sent message is deduplicated (BR-TECH-08). */
  clientMessageId: string;
  /** Not blank, at most 4000 characters (BR-MSG-02). */
  body: string;
  /** Message of the same conversation this one replies to (BR-MSG-02). */
  replyToMessageId?: string;
};

/** Outcome of `MessageRepository.sendMessage` (BR-TECH-08, BR-SOC-02, BR-SOC-04). */
export type SendMessageOutcome = {
  message: ChatMessage;
  /** True when the client re-sent a message that already exists: nothing new was stored, nobody must be notified. */
  deduplicated: boolean;
  /** Users with access to the conversation, minus the sender and users blocked with the sender. Empty when deduplicated. */
  recipientUserIds: string[];
  /** `recipientUserIds` minus the users who muted the conversation: the users to push to. Empty when deduplicated. */
  pushRecipientUserIds: string[];
};

/** Outcome of `MessageRepository.deleteMessage` (BR-MSG-03). */
export type DeleteMessageOutcome = { conversationId: string };

/** Outcome of `react` and `unreact`: whether a reaction was added or removed. */
export type ReactionOutcome = { changed: boolean };

/** Target of a conversation, as listed to a member. */
export type ConversationTargetInfo =
  | { kind: 'circle'; circleId: string; name: string }
  | { kind: 'community'; communityId: string; name: string }
  | {
      kind: 'occurrence';
      occurrenceId: string;
      key: OccurrenceKey;
      title: string;
      startsAt: Date;
    };

/** One conversation of `listMyConversations` (BR-MSG-01, BR-MSG-02). */
export type MyConversation = {
  conversationId: string;
  target: ConversationTargetInfo;
  /** Last message visible to the viewer, `null` when there is none. */
  lastMessage: {
    id: string;
    sender: MessageSender;
    /** The first 200 characters of the body. */
    bodyPreview: string;
    createdAt: Date;
  } | null;
  /** Messages after the viewer's read pointer, own messages and blocked users left out (BR-MSG-02). */
  unreadCount: number;
  muted: boolean;
};

/** Outcome of `getUnreadCounts` (BR-MSG-02). */
export type UnreadCounts = {
  total: number;
  /** Only conversations with at least one unread message. */
  byConversation: { conversationId: string; unread: number }[];
};

/** A member who has read a message ("seen by", BR-MSG-02). */
export type MessageReader = {
  userId: string;
  username: string;
  avatarPath: string | null;
};

/** Outcome of `markRead`: the read pointer after the call (it only moves forward). */
export type MarkReadOutcome = { lastReadMessageId: string };

/** Type of a real-time chat event sent with PostgreSQL NOTIFY (BR-TECH-09). */
export type ChatEventType =
  'message_created' | 'message_edited' | 'message_deleted' | 'reaction_changed';

/**
 * A real-time chat event (BR-TECH-09). It carries ids only: reload the message with
 * `MessageRepository.getMessage(viewerId, messageId)` for each connected viewer, so that access and blocking apply.
 */
export type ChatEvent = {
  type: ChatEventType;
  conversationId: string;
  messageId: string;
};
