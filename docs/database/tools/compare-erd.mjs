// Compares the ERD (docs/database/diagram/teamdrop-erd.drawio) with the real schema (db/schema.sql): tables and
// columns missing on either side, and nullability differences. Writes docs/database/internal/erd-schema-diff.md.
// The ERD is generated from erd-tools/spec.mjs (outside the repository): fix spec.mjs, then regenerate the diagram.
// Run from the repository root: npm run docs:erd-check
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const xml = readFileSync(resolve(root, 'docs/database/diagram/teamdrop-erd.drawio'), 'utf8');
const schema = readFileSync(resolve(root, 'db/schema.sql'), 'utf8');

const decode = (s) =>
  s
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&')
    .replace(/<br\s*\/?>/g, ' ').replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').trim();

// ERD: cells with a table style are tables; their rows' cells hold "name: type" (a trailing ? means nullable).
const cells = [...xml.matchAll(/<mxCell\b([^>]*)>/g)].map((m) => {
  const attr = (name) => new RegExp(`\\b${name}="([^"]*)"`).exec(m[1])?.[1] ?? '';
  return { id: attr('id'), value: decode(attr('value')), parent: attr('parent'), style: attr('style') };
});
const children = new Map();
for (const c of cells) children.set(c.parent, [...(children.get(c.parent) ?? []), c]);
const erd = new Map();
for (const table of cells.filter((c) => c.style.includes('shape=table'))) {
  // "(derived)" marks the analytics tables. Reference boxes ("user_account (Accounts & profiles)") repeat a table of
  // another page, and "(pending)" tables are not built: both are skipped.
  const name = table.value.replace(/\s*\(derived\)$/, '');
  if (name === '' || /\(/.test(name)) continue;
  const columns = erd.get(name) ?? new Map();
  for (const row of children.get(table.id) ?? []) {
    for (const cell of children.get(row.id) ?? []) {
      const match = /^([a-z_0-9]+): ([a-z_0-9]+(?:\([A-Za-z]+\))?)(\?)?( \(pending\))?/.exec(cell.value);
      // A "(pending)" column (PENDING-TEAM) is not built.
      if (match && match[4] === undefined) columns.set(match[1], { type: match[2], nullable: match[3] === '?' });
    }
  }
  erd.set(name, columns);
}
const pendingInErd = [...new Set(cells
  .filter((c) => c.style.includes('shape=table') && /\(pending\)/.test(c.value))
  .map((c) => c.value.replace(/\s*\(pending\)/, '')))];

// Schema: CREATE TABLE public.<name> ( <column> <type> ... NOT NULL, ... );
const db = new Map();
for (const m of schema.matchAll(/CREATE TABLE public\.(\w+) \(\n([\s\S]*?)\n\);/g)) {
  const columns = new Map();
  for (const line of m[2].split('\n')) {
    const col = /^\s{4}(\w+) (.+?),?$/.exec(line);
    if (!col || col[1] === 'CONSTRAINT') continue;
    columns.set(col[1], { type: col[2].split(' ')[0], nullable: !/NOT NULL/.test(col[2]) });
  }
  db.set(m[1], columns);
}
const ignored = new Set(['schema_migrations', 'spatial_ref_sys']);

const lines = ['# ERD vs schema', '', '> Generated by `npm run docs:erd-check`. ERD: `docs/database/diagram/teamdrop-erd.drawio`.', '> Schema: `db/schema.sql`. Fix `erd-tools/spec.mjs`, regenerate the diagram, then run the check again.', ''];
const missingInDb = [...erd.keys()].filter((t) => !db.has(t)).sort();
const missingInErd = [...db.keys()].filter((t) => !erd.has(t) && !ignored.has(t)).sort();
lines.push('## Tables', '');
lines.push(`- In the ERD, not in the schema: ${missingInDb.length ? missingInDb.map((t) => `\`${t}\``).join(', ') : 'none'}`);
lines.push(`- In the schema, not in the ERD: ${missingInErd.length ? missingInErd.map((t) => `\`${t}\``).join(', ') : 'none'}`);
lines.push(`- Pending in the ERD (not built, PENDING-TEAM): ${pendingInErd.map((t) => `\`${t}\``).join(', ') || 'none'}`);
lines.push('', '## Columns', '', '| Table | Column | ERD | Schema |', '|---|---|---|---|');
let differences = 0;
for (const [table, columns] of [...erd.entries()].sort()) {
  const real = db.get(table);
  if (!real) continue;
  for (const [name, col] of columns) {
    const r = real.get(name);
    if (!r) {
      lines.push(`| \`${table}\` | \`${name}\` | ${col.type}${col.nullable ? '?' : ''} | missing |`);
      differences += 1;
    } else if (r.nullable !== col.nullable) {
      lines.push(`| \`${table}\` | \`${name}\` | ${col.nullable ? 'nullable' : 'not null'} | ${r.nullable ? 'nullable' : 'not null'} |`);
      differences += 1;
    }
  }
  for (const [name, r] of real) {
    if (!columns.has(name)) {
      lines.push(`| \`${table}\` | \`${name}\` | missing | ${r.type}${r.nullable ? ' (nullable)' : ''} |`);
      differences += 1;
    }
  }
}
if (differences === 0) lines.push('| (none) | | | |');
lines.push('');
writeFileSync(resolve(root, 'docs/database/internal/erd-schema-diff.md'), lines.join('\n'));
console.log(`ERD tables: ${erd.size}, schema tables: ${db.size}; ${missingInDb.length + missingInErd.length} table and ${differences} column differences.`);
